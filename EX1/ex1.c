#include <stdio.h>
int main() 
{
    const double n = 0.90;             // Efficiency of The Conversion (90%)
    const double m_p_cm = 1000.0;      // Mass per Cublic Meter (kg/m^3)
    const double g = 9.80;             // Gravitational Constant (m/s^2)
    const double W_to_MW = 1000000.0;  // Watts to MegaWatts (1 MW = 10^6 W)
    
    double h;          // Height of the Dam (m)
    double flow_r;     // Flow Rate of Water (m^3/s)
    double m;          // Mass of water flowing per second (kg/s)
    double work;       // Work done by gravity (J)
    double p_W;        // Power in Watts (W)
    double p_MW;       // Power in Megawatts (MW)

    printf("Enter the Height of the Dam (In Meters):");
    scanf("%lf", &h);

    printf("Enter the Flow Rate of Water (In Cubic Meters per Second):");
    scanf("%lf", &flow_r);

    m = flow_r * m_p_cm ;
    work = m * g * h;
    p_W = n * work;
    p_MW = p_W / W_to_MW;

    printf("Predicted Power Generated by the Hydroelectric Dam: %.2f megawatts\n", p_MW);

    return 0;
}
